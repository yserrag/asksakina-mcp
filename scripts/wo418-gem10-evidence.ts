/**
 * WO#418 — evidence for Gem 10 (docs/wo418-gem10-evidence.md), report only.
 *
 *  1. Condition 4: `laylat-al-qadr-afw-3513` printed from the built
 *     444-record bundle, with its own character counts, and the full
 *     check-dua-chars.ts output for that bundle.
 *  2. Gate 3: a local get_dua({ context: "morning" }) response, in full.
 *  3. Before and after of the D00143 and D00154 dua_blocks (the two label
 *     cases) and of D00143's grading line (Part E).
 *
 * Run (after bundle-data): npx tsx scripts/wo418-gem10-evidence.ts
 */

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { getDuaHandler } from '../src/tools/get-dua.js'
import { getDuaRecordById } from '../src/data/duas.js'

const DIR = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(DIR, '..', '..')

async function main() {
  const bundle = JSON.parse(readFileSync(path.join(DIR, '..', 'data', 'duas.json'), 'utf-8')) as Record<string, unknown>[]
  const rec = bundle.find((d) => d.id === 'laylat-al-qadr-afw-3513')
  if (!rec) throw new Error('laylat-al-qadr-afw-3513 not in the bundle')
  const strings = Object.values(rec).filter((v): v is string => typeof v === 'string')
  const count = (re: RegExp) => strings.reduce((n, s) => n + (s.match(re)?.length ?? 0), 0)
  const counts = {
    'U+2014 (em dash)': count(/—/g),
    'U+FDFA': count(/ﷺ/g),
    'PBUH (whole word, any case)': count(/\bPBUH\b/gi),
    'SAW (whole word, upper case)': count(/\bSAW\b/g),
    'U+0671 (in arabic)': ((rec.arabic as string).match(/ٱ/g) ?? []).length,
  }
  const check = execFileSync('npx', ['tsx', path.join(DIR, 'check-dua-chars.ts')], { encoding: 'utf-8' })
  const morning = await getDuaHandler({ context: 'morning' } as any)
  const block = (id: string) => getDuaRecordById(id)!.dua_block

  const L: string[] = []
  L.push("# WO#418: evidence for Gem 10 (the WO#417 payload's conditions)")
  L.push('')
  L.push(`GENERATED by \`mcp-server/scripts/wo418-gem10-evidence.ts\` from the bundle built on this branch (${bundle.length} records). Report only.`)
  L.push('')
  L.push('## Condition 4: `laylat-al-qadr-afw-3513`, as bundled')
  L.push('')
  L.push('```json')
  L.push(JSON.stringify(rec, null, 2))
  L.push('```')
  L.push('')
  L.push('Counts in this record\'s strings:')
  L.push('')
  L.push('| character or token | count |')
  L.push('|---|---|')
  for (const [k, v] of Object.entries(counts)) L.push(`| ${k} | ${v} |`)
  L.push('')
  L.push('`check-dua-chars.ts` on the same bundle (runs after every `bundle-data`):')
  L.push('')
  L.push('```text')
  L.push(check.trim())
  L.push('```')
  L.push('')
  L.push('## Conditions 1 and Part E: the dua_block lines that changed')
  L.push('')
  L.push('D00143 (Ayat al-Kursi, morning; Pickthall English verified; Gem 4 reference):')
  L.push('')
  L.push('```text')
  L.push(block('D00143'))
  L.push('```')
  L.push('')
  L.push('D00154 (9:129 clause; corpus English, not Pickthall, so no Pickthall claim):')
  L.push('')
  L.push('```text')
  L.push(block('D00154'))
  L.push('```')
  L.push('')
  L.push('## Gate 3: `get_dua({ context: "morning" })`, in full')
  L.push('')
  L.push('Called locally on this branch. Note `_sakina_meta.presentation_contract.quran` (no `translator`: D00154 is in this response and its English is not Pickthall), the scoped ungraded directive in `CRITICAL_RULES`, and the em dash rule.')
  L.push('')
  L.push('```json')
  L.push(JSON.stringify(morning, null, 2))
  L.push('```')
  L.push('')
  const out = path.join(ROOT, 'docs', 'wo418-gem10-evidence.md')
  writeFileSync(out, L.join('\n'))
  console.log(`wrote ${out}; 3513 counts ${JSON.stringify(counts)}`)
}

main()
