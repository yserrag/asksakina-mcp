/**
 * Bundle data for standalone MCP server deployment (WO#105 Task 1).
 *
 * The MCP server cannot ship with `../src/...` imports — when
 * published as @asksakina/islamic-knowledge-mcp, the consumer's
 * machine doesn't have the main Sakina monorepo. This script
 * snapshots the required content + safety logic into the package's
 * own `data/` and `src/safety/_synced/` directories.
 *
 * Outputs:
 *   - `mcp-server/data/duas.json`            — the du'a corpus, Gem-2-verified Quranic entries labelled (quranic-labels.ts)
 *   - `mcp-server/data/names.json`           — 99 Names of Allah
 *   - `mcp-server/data/dua-categories.json`  — DUA_CATEGORIES metadata
 *   - `mcp-server/data/thematic-verses.json` — the thematic verse index (WO#386), Arabic from the scripture module
 *   - `mcp-server/data/pickthall.json`       — WO#444: the app's corrected Pickthall, all 6,236 verses, served by get_quran_verse and find_verses
 *   - `mcp-server/src/safety/_synced/crisis-detection.ts`
 *   - `mcp-server/src/safety/_synced/arabic-normalise.ts`
 *   - `mcp-server/src/safety/_synced/crisis-normalise.ts` (WO#391)
 *
 * Why synced TS files (not just keyword JSON): the main app's
 * `detectCrisis` is the canonical safety contract — Gem 3 + Gem 5
 * have signed off on its exact phrase matching, not just on a flat
 * keyword list. Re-implementing the matcher in the MCP server would
 * risk silent drift. Snapshotting the source preserves the contract;
 * a future divergence shows up clearly in `git diff` against the
 * synced files.
 *
 * Run: `npm run bundle-data` from `mcp-server/`. Wired into
 * `prepublishOnly` so `npm publish` always re-bundles first.
 */

