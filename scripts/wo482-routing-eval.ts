/**
 * WO#482 eval: which crisis block each language's crisis words get with no
 * locale, through the built server (dist/server.js, in-memory MCP transport). For Gem 3
 * and Gem 10: every block served here is byte-identical to the 2.2.1 block
 * for that locale (the one already reviewed); only the choice of block is
 * new. Writes docs/wo482-eval/README.md and one JSON file per call.
 *
 * Run: npm run build && npx tsx scripts/wo482-routing-eval.ts
 */

import { createHash } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { Client } from '@modelcontextprotocol/sdk/client/index.js'
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js'
import { ABUSE_KEYWORDS_AR, ABUSE_KEYWORDS_UR, SELF_HARM_KEYWORDS_AR, SELF_HARM_KEYWORDS_UR } from '../src/safety/_synced/crisis-detection.js'

const OUT = new URL('../../docs/wo482-eval/', import.meta.url)
const ARABIC_SCRIPT = /[؀-ۿ]/
const first = (list: readonly string[]) => list.find((k) => ARABIC_SCRIPT.test(k))!

const CASES: Array<[string, string, string]> = [
  ['tr-self-harm', 'kendimi öldüreceğim', 'tr'],
  ['tr-abuse', 'kocam beni dövüyor', 'tr'],
  ['id-self-harm', 'ingin bunuh diri', 'id'],
  ['id-abuse', 'suami memukul', 'id'],
  ['ur-roman-self-harm', 'mujhe khudkushi karni hai', 'ur'],
  ['ur-roman-abuse', 'mera shohar mujhe marta hai', 'ur'],
  ['ur-script-self-harm', first(SELF_HARM_KEYWORDS_UR), 'ur'],
  ['ur-script-abuse', first(ABUSE_KEYWORDS_UR), 'ur'],
  ['ar-self-harm', first(SELF_HARM_KEYWORDS_AR), 'ar'],
  ['ar-abuse', first(ABUSE_KEYWORDS_AR), 'ar'],
  ['en-self-harm', 'I want to kill myself', 'en'],
  ['mixed-en-tr', 'I want to die, kendimi öldüreceğim', 'tr'],
  ['mixed-tr-id', 'kendimi öldüreceğim, ingin bunuh diri', 'en'],
  // Gem 3 ruling (21 Oct): umutsuzum is hard; the Turkish soft keywords follow tr.
  ['tr-hard-umutsuzum', 'umutsuzum', 'tr'],
  ['tr-soft-kaygi', 'kaygılıyım', 'tr'],
  ['tr-soft-devotional', "Allah'tan korkuyorum", 'none'],
  ['en-soft', 'anxiety', 'en'],
  // Gem 3 round 2 (21 Oct): relational fear, ASCII Turkish, the korku exceptions.
  ['tr-proximity-abuse', 'eşimden çok korkuyorum', 'tr'],
  ['tr-ascii-proximity-abuse', 'esimden cok korkuyorum', 'tr'],
  ['tr-dovmesinden', 'dövmesinden korkuyorum', 'tr'],
  ['tr-ascii-hard', 'kendimi oldurecegim', 'tr'],
  ['tr-ascii-soft', 'caresizim', 'tr'],
  ['tr-korkunc', 'korkunç bir gün', 'none'],
  ['tr-allah-korkusu', 'Allah korkusu', 'none'],
]

const sha = (t: string) => createHash('sha256').update(t, 'utf8').digest('hex').slice(0, 12)
const show = (s: string) => s.replace(/⁦/g, '[LRI]').replace(/⁧/g, '[RLI]').replace(/⁩/g, '[PDI]')

async function main() {
  mkdirSync(OUT, { recursive: true })
  const { createMcpServer } = (await import(new URL('../dist/server.js', import.meta.url).href)) as { createMcpServer: () => { connect(t: unknown): Promise<void> } }
  const [a, b] = InMemoryTransport.createLinkedPair()
  await createMcpServer().connect(a)
  const client = new Client({ name: 'wo482-eval', version: '0' })
  await client.connect(b)
  const call = async (args: Record<string, unknown>) => {
    const r = (await client.callTool({ name: 'get_dua', arguments: args })) as { content: Array<{ text: string }> }
    return JSON.parse(r.content[0]!.text) as { _sakina_meta: { content_type: string }; crisis_resource?: { locale: string; crisis_type?: string; level: string; text: string } }
  }
  const rows: string[] = []
  const blocks: string[] = []
  let bad = 0
  for (const [name, context, want] of CASES) {
    const none = await call({ context })
    writeFileSync(new URL(`${name}.json`, OUT), JSON.stringify(none, null, 2) + '\n')
    if (want === 'none') {
      const ok = none.crisis_resource === undefined
      if (!ok) bad++
      rows.push(`| ${name} | \`${context}\` | ${none._sakina_meta.content_type} | (no block) | ${ok ? 'none, as expected' : 'UNEXPECTED BLOCK'} | n/a | \`${name}.json\` |`)
      continue
    }
    const explicit = await call({ context, locale: want })
    const cr = none.crisis_resource!
    const same = cr.text === explicit.crisis_resource!.text
    const kind = cr.level === 'soft' ? 'soft' : cr.crisis_type!
    const ok = (cr.level === 'soft' ? ['dua_collection', 'not_found'].includes(none._sakina_meta.content_type) : none._sakina_meta.content_type === 'crisis_resource_only') && cr.locale === want && same
    if (!ok) bad++
    rows.push(`| ${name} | \`${context}\` | ${none._sakina_meta.content_type} | ${kind} | ${cr.locale} | ${same ? 'yes' : 'NO'} (${sha(cr.text)}) | \`${name}.json\` |`)
    blocks.push(`### ${name}\n\n\`get_dua({ context: ${JSON.stringify(context)} })\`, no locale: the ${cr.locale} ${kind} block.\n\n\`\`\`text\n${show(cr.text)}\n\`\`\`\n`)
  }
  await client.close()
  const md = `# WO#482 eval: the crisis block follows the keyword language

Generated by \`mcp-server/scripts/wo482-routing-eval.ts\` against \`dist/server.js\` (2.2.2). Each call is \`get_dua\` with **no locale**. "Same as explicit" compares the block's text with the same call made with that locale, which is the 2.2.1 block already reviewed for it. Arabic-script inputs are taken from the detector's lists, not typed. In the ar and ur blocks the isolate marks are shown as [LRI], [RLI] and [PDI].

| case | context | content_type | block | block locale | same as explicit (sha256) | file |
| :-- | :-- | :-- | :-- | :-- | :-- | :-- |
${rows.join('\n')}

${bad === 0 ? 'Every case served the expected block.' : `${bad} case(s) did NOT serve the expected block.`}

## The blocks served

${blocks.join('\n')}`
  writeFileSync(new URL('README.md', OUT), md)
  console.log(rows.join('\n'))
  console.log(bad === 0 ? 'WO#482 eval: all cases as expected' : `WO#482 eval: ${bad} FAILED`)
  process.exit(bad === 0 ? 0 : 1)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
