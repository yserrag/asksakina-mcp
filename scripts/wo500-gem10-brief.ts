/**
 * WO#500 (MCP 2.5.1): writes the Gem 10 brief (docs/wo500-gem10.md) from the
 * synced detector and the app's WO#500 fixture, so every phrase in it is the
 * shipped bytes. Under 15 KB, with its own reply rules.
 *
 *   npx tsx scripts/wo500-gem10-brief.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { ABUSE_KEYWORDS_AR, ABUSE_KEYWORDS_BN, ABUSE_KEYWORDS_EN, ABUSE_KEYWORDS_FA, ABUSE_KEYWORDS_ID, ABUSE_KEYWORDS_UR } from '../src/safety/_synced/crisis-detection.js'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const D = JSON.parse(readFileSync(path.resolve(HERE, '..', '..', 'src', 'lib', 'utils', '__tests__', 'wo500-phrases.json'), 'utf-8')) as {
  phrases: Array<{ lang: string; phrase: string; status: string }>
  negative: string[]
  educational: Array<{ lang: string; query: string; note: string; expect: string }>
}
// The WO#500 entries close each list (asserted by the app's wo500-abuse-intent test).
const tail = (list: readonly string[], n: number) => list.slice(list.length - n)
const LISTS: Array<[string, readonly string[], number]> = [
  ['English', ABUSE_KEYWORDS_EN, 27], ['Urdu', ABUSE_KEYWORDS_UR, 4], ['Arabic', ABUSE_KEYWORDS_AR, 5],
  ['Indonesian', ABUSE_KEYWORDS_ID, 3], ['Bengali', ABUSE_KEYWORDS_BN, 3], ['Persian', ABUSE_KEYWORDS_FA, 3],
]
const count = (s: string) => D.phrases.filter((p) => p.status === s).length

const doc = `# WO#500 (MCP 2.5.1, and the app's crisis detector): Gem 10 brief

GENERATED by \`mcp-server/scripts/wo500-gem10-brief.ts\` from the shipped detector (\`src/lib/utils/crisis-detection.ts\`, synced into the MCP) and the WO#500 test fixture. Every phrase below is the stored bytes.

**What changes for an agent:** only which inputs return the abuse resource block. No served string changes: the crisis and support blocks, directives and records are byte-identical to 2.5.0 on all 183 byte-identity calls, for every audience.

## W10-1. 45 new abuse-pathway keywords

${D.phrases.length} phrases were proposed (the Architect's English list, after the false-positive ruling, and Gem 3's ur, pa, tr, ar, id, bn and fa lists). ${count('exact')} were already keywords and ${count('covered')} were covered by a keyword inside them; ${count('gated')} of the exact ones are WO#265 four-gate bare nouns (W10-3). The ${count('new') + count('restored')} below are new keywords (${count('restored')} of them, "locked me inside", restores a hit; W10-2). Each returns \`crisis_resource_only\` with the abuse block on find_verses and get_dua, before any theme: tested with every 2.5.0 theme trigger, in both word orders. Non-Latin strings are stored in their list's normalised form, plain text, with no bidi isolate or invisible mark (Architect overrule of Gem 3's technical note). Their code points are with Gem 2 (\`docs/wo500-gem2-codepoints.md\`).

${LISTS.map(([name, list, n]) => `- **${name}** (${n}): ${tail(list, n).join('; ')}`).join('\n')}

## W10-2. The English word-boundary end (Architect ruling, Gem 3 to confirm)

Every English abuse keyword now ends at a word boundary; an inflection (-ing, -ed, -s, -er) and a repeated final letter still count. Before, they were open at the end, so "abusing me" matched "abusing medication". The Architect also dropped four phrases ("is violent", "he abuses", "she abuses", "they abuse") and named the relation instead ("he is violent", "my father is violent").

These must NOT fire, and do not (tested in the app and the MCP): ${D.negative.map((q) => `"${q}"`).join(', ')}.

Still fire: "he hit me again", "beats me up", "abusive relationships", "being abused by my husband", "she keeps abusing me with drugs".

**No disclosure lost.** Measured against main over 3,288 test strings and 29 phrasings, one hit was lost: "locked me inside" ("locked me in" now ends at "in"). By the Architect's ruling it is restored as its own keyword, with "locks me in" and "locks me inside"; "locked me in the house" is covered by "locked me in". Gem 3 to confirm these four with the narrowing.

Self-harm keywords keep the open end.

## W10-3. Educational questions

| lang | result |
|---|---|
${D.educational.map((e) => `| ${e.lang} | ${e.expect === 'abuse' ? 'abuse block' : 'no crisis block'}: ${e.note} |`).join('\n')}

Persian and Bengali "domestic violence" stay under the WO#265 four-gate (a locked ruling): a short informational question does not fire, where the same question in ur, ar, tr, id and English does.

## W10-4. The 2.5.0 abuse-word hold stays

The bare words ("abuse", "abusive", "violence" and their forms) are still not crisis keywords; a query carrying one reaches none of the 2.5.0 themes, as you passed in G10-9. The next crisis-routing release (Gem 3, dhulm framing) is logged in \`docs/CURRENT_STATE.md\`.

## How to reply

For each item (W10-1 to W10-4), one line: the id, then **PASS**, **CHANGE** with what to change, or **BLOCK** with the reason. W10-2 is marked for Gem 3 to confirm; your PASS covers the egress side only. Do not restate an item you pass.
`
const out = path.resolve(HERE, '..', '..', 'docs', 'wo500-gem10.md')
writeFileSync(out, doc)
const kb = Buffer.byteLength(doc, 'utf8') / 1024
console.log(`wo500-gem10.md  ${kb.toFixed(1)} KB`)
if (kb >= 15) throw new Error('over 15 KB; split it')
