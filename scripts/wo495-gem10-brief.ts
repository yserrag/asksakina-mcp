/**
 * WO#495: writes the Gem 10 brief (docs/wo495-gem10-part1..3.md) from the
 * shipped code, so every string in it is the served bytes, not a retyping.
 * Each part stays under 15 KB and carries its own reply rules.
 *
 *   npx tsx scripts/wo495-gem10-brief.ts
 */

import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { DAWAH_ADAB_BLOCK } from '../src/contracts/instructions.js'
import { LEARN_RESOURCE_SHA256, REVERT_NOTES } from '../src/contracts/learn-content.js'
import { LEARN_RESOURCES } from '../src/contracts/learn-resources.js'
import { AUDIENCE_NOTE_DIRECTIVE } from '../src/contracts/presentation.js'
import { ABUSE_WORDS } from '../src/data/thematic.js'
import { OUTSIDE_MODULE, THEMES_2_5_0 } from '../src/data/themes-2-5-0.js'
import { firstStepsPrompt, JOURNEY_DUA_IDS, JOURNEY_STRINGS, PROMPT_STRINGS, whatMuslimsBelievePrompt } from '../src/prompts/learning-journeys.js'
import { TEACH_ENTRIES } from '../src/teach/entries.js'
import { HEALING_DIRECTIVE } from '../src/tools/find-verses.js'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const DOCS = path.resolve(HERE, '..', '..', 'docs')
const sha = (s: string) => createHash('sha256').update(s, 'utf8').digest('hex')
const quote = (s: string) => s.split('\n').map((l) => `> ${l}`).join('\n')
const fence = (s: string) => '```text\n' + s + '\n```'

const HEADER = (n: number) => `# WO#495 (MCP 2.5.0): Gem 10 brief, part ${n} of 3

GENERATED by \`mcp-server/scripts/wo495-gem10-brief.ts\` from the shipped code: every string below is the bytes the server sends. Each sha256 is of the UTF-8 text.
`

const RULES = (ids: string) => `## How to reply to this part

For each item (${ids}), one line: the item id, then **PASS**, **CHANGE** with the exact replacement text, or **BLOCK** with the reason. Judge only what this part shows. Do not rewrite Qur'an text, hadith text, gradings or Arabic: those are Gem 2's and Gem 4's, and they are ruled. Do not restate an item you pass.
`

// ── Part 1: directives, prompt strings, prompt messages ─────────────────────
const shared = new Map<string, string>([
  [PROMPT_STRINGS.follow, '[FOLLOW]'],
  [DAWAH_ADAB_BLOCK, '[DAWAH_ADAB_BLOCK]'],
  [PROMPT_STRINGS.block, '[BLOCK]'],
])
const labelled = (text: string) => text.split('\n').map((l) => shared.get(l) ?? l).join('\n')
const p1 = [
  HEADER(1),
  `## What 2.5.0 adds (the whole agent-facing surface)

- Two prompts: \`what_muslims_believe\` and \`first_steps_new_muslim\` (this part).
- Two new directive lines: healing (G10-1) and \`audience_note\` (G10-2) (this part).
- Six resources the prompts read (part 2).
- Seven notes for a new Muslim, served as \`audience_note\` with \`audience: "revert"\` only; the 2:256 teach entry; fifteen find_verses themes; the abuse-word hold; one du'a id on the allowlist (part 3).

Three lines are unchanged from 2.4.0's prompts (WO#489) and shown below only by label: [FOLLOW] and [BLOCK] (text here), and [DAWAH_ADAB_BLOCK], the server's da'wah adab block, as in its \`instructions\`.

${fence(`[FOLLOW] ${PROMPT_STRINGS.follow}\n[BLOCK] ${PROMPT_STRINGS.block}`)}
`,
  `## G10-1. The healing directive (new; the Builder's draft from Gem 4's hifz al-nafs note)

Added to CRITICAL_RULES on every find_verses response that reaches the healing theme. sha256 \`${sha(HEALING_DIRECTIVE)}\`.

${fence(HEALING_DIRECTIVE)}
`,
  `## G10-2. The audience_note directive (new; the Builder's draft)

Added to CRITICAL_RULES whenever a record carries an \`audience_note\`. sha256 \`${sha(AUDIENCE_NOTE_DIRECTIVE)}\`. The note itself is served only with \`audience: "revert"\`, only in English, and never where teach is withheld (crisis, a support block, the grief route).

${fence(AUDIENCE_NOTE_DIRECTIVE)}
`,
  `## G10-3. The prompts' new strings

Titles, descriptions and argument descriptions are the Builder's; the message lines are the approved journey text (docs/wo492-journeys-part4.md), except \`callDua\`: the approved line said "context repentance, limit 1", which serves D00231, not the ruled du'a, so it now names the id (D00234, Sahih al-Bukhari 744). Arguments outside the listed values are refused with -32602, and the value is never echoed.

| key | string |
|---|---|
${Object.entries(JOURNEY_STRINGS).map(([k, v]) => `| \`${k}\` | ${v.replace(/\|/g, '\\|')} |`).join('\n')}
`,
  `## G10-4. The messages, whole

\`what_muslims_believe\` (no argument; \`revert\` and \`practising\` change only the second line). sha256 \`${sha(whatMuslimsBelievePrompt({}).messages[0]!.content.text)}\`.

${fence(labelled(whatMuslimsBelievePrompt({}).messages[0]!.content.text))}
`,
  ...['1', '2', '3', '4'].map((step) => {
    const t = firstStepsPrompt({ step }).messages[0]!.content.text
    return `\`first_steps_new_muslim\` step ${step}${step === '1' ? ' (also the no-argument default)' : ''}. sha256 \`${sha(t)}\`.\n\n${fence(labelled(t))}\n`
  }),
  RULES('G10-1 to G10-4'),
].join('\n')

// ── Part 2: the six resources ───────────────────────────────────────────────
const p2 = [
  HEADER(2),
  `## G10-5. The six resources

Read by the prompts and served verbatim (\`resources/read\`, text/markdown). Each body is built by script from the app's own reviewed seed modules and the Gems' rulings; the build fails if the committed text differs. Content approvals: Gems 1, 3, 5, 6 and 7 (docs/wo495-architect.md). The Builder applied one mechanical rule: an em dash the draft struck became a comma. Two points to look at:
- \`#first-prayer\`: the draft cut the Al-Fatiha block, so the sentence before it now ends "...the opening chapter of the Quran in Arabic." (Architect). The prompt tells the agent to point the user to the app for Al-Fatiha and not to quote it from memory.
- \`#forgiven\`: 8:38 is quoted whole, so it includes its warning clause.
`,
  ...LEARN_RESOURCES.map((r) => `### ${r.uri}\n\nname \`${r.name}\`; title "${r.title}"; sha256 \`${LEARN_RESOURCE_SHA256[r.uri]}\`\n\nDescription: ${r.description}\n\n${quote(r.text)}\n`),
  RULES('G10-5, one line per resource, by URI'),
].join('\n')

// ── Part 3: notes, 2:256, themes, the hold, the allowlist ───────────────────
const e256 = TEACH_ENTRIES['verse:2:256' as keyof typeof TEACH_ENTRIES]!
const p3 = [
  HEADER(3),
  `## G10-6. Notes for a new Muslim (\`audience_note\`, revert only)

Re-sent after Gem 10's BLOCK: the 39:53 note quoted and cited 25:70, so it is removed from 2.5.0 (Architect, docs/wo495-architect.md §10); Gem 6 re-authors a 39:53-only note later. A test now fails if any note cites a verse other than its own record's, or carries 8 or more consecutive words of another verse's Pickthall. ${Object.keys(REVERT_NOTES).length} notes remain.

Each note is served as \`{ audience: "revert", text, citations, note_block }\`; \`note_block\` is the text, then (with citations) a newline and the citations, as \`context_block\` is. Authors: Gem 6 (names, du'a), the app's revert modules (verses), with Gem 7's notes and the Architect's corrections.

${Object.entries(REVERT_NOTES)
  .map(([k, n]) => `### ${k}\n\nCitations: ${n.citations.length ? n.citations.map((c) => (c.grading ? `${c.text} (${c.grading})` : c.text)).join('; ') : 'none'}. sha256 of text \`${sha(n.text)}\`.\n\n${quote(n.text)}\n`)
  .join('\n')}`,
  `## G10-7. Teach entry verse:2:256 (publish sign-off)

Field 1 (Gem 2): ${JSON.stringify(e256.key_word.words)}, root ${e256.key_word.root} (${e256.key_word.root_transliteration}), gloss "${e256.key_word.gloss}". Field 2: none (rejected by Gem 4). Field 4 (Gem 3):

${quote(e256.reflection!.text)}

The release gate (run by mcp-deploy before any deploy) refuses this entry until you sign it, so 2.5.0 cannot deploy before then.
`,
  `## G10-8. The fifteen themes (Gem 2 + Gem 4, Gem 3's vetoes)

| theme | verses, in order | triggers |
|---|---|---|
${THEMES_2_5_0.map((t) => `| ${t.theme} | ${t.refsByTrigger ? `${t.refs.join(', ')}; ${Object.keys(t.refsByTrigger).join(', ')}: ${[...new Set(Object.values(t.refsByTrigger).flat())].join(', ')} only` : t.refs.join(', ')} | ${[...t.words, ...t.phrases].join(', ')} |`).join('\n')}

- companionship carries the soft support block and no teach or note.
- healing carries G10-1.
- ${OUTSIDE_MODULE.join(' and ')} take their Arabic from public/quran with the scripture module's one transform (the module does not carry them yet).
`,
  `## G10-9. The abuse-word hold (the Builder's; also to Gem 3)

The crisis detector does not read these words alone (WO#488 E.5 ruled "abuse" not_found with no block): ${ABUSE_WORDS.join(', ')}. Without a hold, "my parents abuse me" would reach 17:24 and "abusive marriage" 30:21. A query carrying one of them reaches none of the fifteen themes and is answered as 2.4 answered it (usually not_found). Crisis routing is unchanged, and every hard crisis keyword still beats every new trigger (tested in both word orders).
`,
  `## G10-10. One id on the get_dua allowlist

\`get_dua\` resolves an id only from its allowlist (WO#390: an open id lookup would make the corpus enumerable). 2.5.0 adds ${JOURNEY_DUA_IDS.join(', ')} (Sahih al-Bukhari 744), the du'a \`first_steps_new_muslim\` step 2 names. The list is now D00060, D00068, D00234.
`,
  RULES('G10-6 to G10-10'),
].join('\n')

// \`--part N\` writes only that part (a re-sent section must not rewrite the parts already ruled on).
const only = process.argv.includes('--part') ? Number(process.argv[process.argv.indexOf('--part') + 1]) : null
const parts = [p1, p2, p3]
parts.forEach((p, i) => {
  if (only !== null && only !== i + 1) return
  const file = path.join(DOCS, `wo495-gem10-part${i + 1}.md`)
  writeFileSync(file, p)
  const kb = Buffer.byteLength(p, 'utf8') / 1024
  console.log(`${path.basename(file)}  ${kb.toFixed(1)} KB`)
  if (kb >= 15) throw new Error(`${path.basename(file)} is ${kb.toFixed(1)} KB; split it`)
})
